#!/usr/bin/env node
// Writes data/names/content-src/similar-candidates.json (PRD name-detail §6.1): for every deck
// name, the deck names isCandidate() proposes as forms of it, most given in 2024 first. The
// details batches review these lists; they don't invent their own.
//
//   node scripts/names-content/similar-candidates.mjs
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { deckOrder } from "./details-batches.mjs";
import { isCandidate } from "./similar-rules.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = "data/names/content-src/similar-candidates.json";

const order = deckOrder();
const names = {};
for (const name of order) names[name] = order.filter((other) => isCandidate(name, other));

const file = {
  _about:
    "Candidate similar names per deck name, from scripts/names-content/similar-rules.mjs (generous on purpose). Generated by scripts/names-content/similar-candidates.mjs; don't edit. The details batches pick the real forms from these lists (PRD name-detail §6.3). Names and lists are in deck order (2024 births, most first).",
  names,
};
writeFileSync(resolve(root, OUT), JSON.stringify(file, null, 1) + "\n");

const counts = Object.entries(names).map(([name, list]) => [name, list.length]);
const withAny = counts.filter(([, n]) => n > 0).length;
const total = counts.reduce((sum, [, n]) => sum + n, 0);
const top = [...counts].sort((a, b) => b[1] - a[1]).slice(0, 10);
console.log(`${OUT}: ${counts.length} names, ${withAny} with ≥ 1 candidate`);
console.log(`average ${(total / counts.length).toFixed(2)} per name, ${(total / withAny).toFixed(2)} per name that has any`);
console.log(`most: ${top.map(([name, n]) => `${name} ${n}`).join(", ")}`);
